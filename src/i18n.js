const langOf = (header) => (/^\s*en\b/i.test(header || '') ? 'en' : 'vi');
const t = (code, lang = 'vi') => messages[lang]?.[code] || messages.vi[code] || null;

const fill = (s, params) => String(s).replace(/\{(\w+)\}/g, (_, k) => (params?.[k] ?? '')).replace(/\s+$/, '').replace(/\s{2,}/g, ' ');

function renderNotification(kind, params, lang = 'vi') {
  const tpl = notifications[lang]?.[kind] || notifications.vi[kind] || ['', ''];
  return { title: fill(tpl[0], params), text: fill(tpl[1], params) };
}

module.exports = { t, langOf, renderNotification, messages };
